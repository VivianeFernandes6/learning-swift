import UIKit

"""
para criar uma variável:
1. eu utilizo a keyword var
2. dou um espaço e digito o nome que eu quero para essa variável
3. atribuo valor a esta variável usando =
4. dou um espaço e digito o valor que quero atribuir a esta variável
"""
var greeting = "Hello, playground"
// visualizo valor da variável, imprimindo na tela
print(greeting)

// como é uma VARIÁVEL
var name = "Vania"
print(name)
// eu posso alterar o valor dela
name = "Tom"
print(name)

var lastName: String = "Araújo"
print(lastName)

lastName = "Souza"
print(lastName)

// eu posso ter dois códigos diferentes na mesma linha, só separando por ;
// apesar de que é muito mais limpo (do meu ponto de vista) pular linha, mas é uma alternativa
var idade: Int = 24; var idade2: Int = 23
print(idade)
print(idade2)


let address = "Rua das Flores, 123"
print(address)

let isBeautiful: Bool = true
print(isBeautiful)

var hairColor: String = "Ruivo"
print(hairColor)

